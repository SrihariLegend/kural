BAD_PATH = re.compile(r"(?i)(^|/)(vendor|vendored|third[_-]?party|thirdparty|node_modules|external|extern|"
                      r"deps|bower_components|\.git|build|dist|out|autom4te\.cache|contrib/[^/]*/upstream)/")
GENERATED = re.compile(r"(?i)(generated by|auto-?generated|automatically generated|do not edit|"
                       r"this file was generated|machine generated|created by bison|lex\.yy\.c|"
                       r"generated from .* by|@generated)")
SHEBANG = re.compile(rb"^#!\s*(?:/usr/bin/env\s+)?\S*/?(?:ba|z|k|da|a)?sh\b")


def language_of(path: str, head: bytes) -> str | None:
    name = os.path.basename(path)
    low = name.lower()
    if low.endswith((".c", ".h")):
        return "C"
    if low.endswith((".sh", ".bash", ".zsh", ".ksh")) or low in {".bashrc", ".zshrc", ".profile", "bashrc", "zshrc"}:
        return "Shell"
    if low in {"makefile", "gnumakefile", "bsdmakefile"} or low.endswith(".mk"):
        return "Makefile"
    if low.startswith("dockerfile") or low.endswith(".dockerfile"):
        return "Dockerfile"
    if "." not in name and SHEBANG.match(head):
        return "Shell"
    return None


def code_reject(path: str, code: str) -> str | None:
    n = len(code)
    if n < 100:
        return "too_short"
    if n > 200_000:
        return "too_long"
    if BAD_PATH.search("/" + path) or ".min." in path:
        return "vendored_path"
    if GENERATED.search(code[:2000]):
        return "generated"
    lines = code.split("\n")
    if len(lines) < 5:
        return "too_few_lines"
    if max(map(len, lines)) > 1000:
        return "long_line"
    if n / len(lines) > 100:
        return "long_mean_line"
    alnum = sum(ch.isalnum() for ch in code)
    if alnum / n < 0.3:
        return "low_alnum"
    words = code.split()
    if words and sum(w.startswith(("0x", "0X")) for w in words) / len(words) > 0.25:
        return "data_table"
    return None


def make_doc(code: str, path: str, repo: str, lang: str, licence: str) -> dict:
    code = code.replace("\r\n", "\n").rstrip() + "\n"
    return {"text": f"File: {path}\n\n{code}", "source": SOURCE,
            "meta": {"repo": repo, "path": path, "language": lang, "license": licence}}


# ---------------------------------------------------------------- curated repos

def clone_curated() -> None:
    CURATED_DIR.mkdir(parents=True, exist_ok=True)
    env = {**os.environ, "GIT_TERMINAL_PROMPT": "0"}
    for name, url, _lic, sparse in CURATED:
        dest = CURATED_DIR / name
        if (dest / ".git").exists():
            continue
        log(f"clone {name}")
        try:
            if sparse:
                subprocess.run(["git", "clone", "-q", "--depth", "1", "--filter=blob:none", "--sparse", url, str(dest)],
                               check=True, env=env, timeout=1800)
                subprocess.run(["git", "-C", str(dest), "sparse-checkout", "set", *sparse], check=True, env=env,
                               timeout=1800)
            else:
                subprocess.run(["git", "clone", "-q", "--depth", "1", url, str(dest)], check=True, env=env, timeout=1800)
        except Exception as e:
            log(f"clone {name} failed: {e}")


def produce_curated(name: str, drops):
    lic = next(l for n, _u, l, _s in CURATED if n == name)
    root = CURATED_DIR / name
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d != ".git")
        for fn in sorted(filenames):
            p = Path(dirpath) / fn
            if p.is_symlink() or not p.is_file():
                continue
            rel = str(p.relative_to(root))
            try:
                raw = p.read_bytes()
            except OSError:
                continue
            lang = language_of(rel, raw[:64])
            if lang is None:
                continue
            try:
                code = raw.decode("utf-8")
            except UnicodeDecodeError:
                drops["not_utf8"] += 1
                continue
            r = code_reject(rel, code)
            if r:
                drops[r] += 1
                continue
            yield make_doc(code, f"{name}/{rel}", name, lang, lic)


# ---------------------------------------------------------------- github-code-clean

def produce_github(shard: int, drops, only_c: bool = False):
    import pyarrow as pa
    import pyarrow.compute as pc
    import pyarrow.parquet as pq
    from huggingface_hub import hf_hub_download

    fname = f"data/train-{shard:05d}-of-{N_SHARDS:05d}.parquet"
    for attempt in range(6):
        try:
            local = hf_hub_download(REPO, fname, repo_type="dataset", local_dir=str(RAW / "ghcode"))
            break
        except Exception as e:
            log(f"download {fname} failed ({e}); retry {attempt + 1}")
            time.sleep(30 * (attempt + 1))
    else:
        raise RuntimeError(fname)
    langs = {"C"} if only_c else (LANGS if shard < C_SHARDS else LANGS - {"C"})
    try:
        t = pq.read_table(local, columns=["code", "repo_name", "path", "language", "license"])
        mask = pc.and_(pc.is_in(t["language"], value_set=pa.array(sorted(langs))),
                       pc.is_in(t["license"], value_set=pa.array(sorted(PERMISSIVE))))
        t = t.filter(mask)
        for code, repo, path, lang, lic in zip(*(t[c].to_pylist() for c in
                                                 ("code", "repo_name", "path", "language", "license"))):
            r = code_reject(path, code)
            if r:
                drops[r] += 1
                continue
            doc = make_doc(code, path, repo, lang, lic)
            if only_c:
                doc["source"] = "code_c_more"
            yield doc
    finally:
        os.unlink(local)


def produce(task, drops):
    kind, arg = task
    if kind == "curated":
        yield from produce_curated(arg, drops)
    elif kind == "c_more":
        yield from produce_github(arg, drops, only_c=True)
    else:
        yield from produce_github(arg, drops)


FILTERS = Filters(langid=False, prose=False, spam=False, min_chars=100, max_chars=250_000)


def tasks_all() -> list:
    return ([(f"a-{n}", ("curated", n)) for n, *_ in CURATED] +
            [(f"g-{s:05d}", ("github", s)) for s in range(N_SHARDS)])


def main() -> None:
    mode = sys.argv[1] if len(sys.argv) > 1 else "all"
    os.environ.setdefault("HF_HOME", str(RAW.parent / "hf_home"))
    if mode in ("curated", "all"):
        clone_curated()
        run_tasks(SOURCE, [t for t in tasks_all() if t[0].startswith("a-") and (CURATED_DIR / t[1][1]).exists()],
                  produce, FILTERS)
    if mode in ("github", "all"):
        run_tasks(SOURCE, [t for t in tasks_all() if t[0].startswith("g-")], produce, FILTERS, workers=10)
    if mode in ("c_more", "all"):
        tasks = [(f"c-{s:05d}", ("c_more", s)) for s in C_MORE_SHARDS]
        run_tasks("code_c_more", tasks, produce, FILTERS, workers=10)
        finalize("code_c_more", [t for t, _ in tasks], extra_stats={
            "origin": f"https://huggingface.co/datasets/{REPO} (C files of shards {C_MORE_SHARDS.start}-"
                      f"{C_MORE_SHARDS.stop - 1})",
            "licence": "per file (meta.license): MIT, Apache-2.0, BSD-2/3-Clause, ISC, Unlicense, CC0"})
    if mode in ("finalize", "all"):
        from common import WORK
        ids = [tid for tid, _ in tasks_all() if (WORK / SOURCE / f"part-{tid}.json").exists()]
        finalize(SOURCE, ids, extra_stats={
            "origin": f"https://huggingface.co/datasets/{REPO} + curated repositories (see data_tools/code.py CURATED)",
            "licence": "per file (meta.license): MIT, Apache-2.0, BSD-2/3-Clause, ISC, 0BSD, Unlicense, CC0, zlib, "
                       "curl, public domain; licence notices inside files are kept"})


if __name__ == "__main__":
    main()
