"""C, shell, Makefile and Dockerfile code -> data/clean/code/.

Two inputs:

1. codeparrot/github-code-clean (880 parquet shards, 314 GB, GitHub files with an SPDX
   licence detected per repository). Only permissively licensed files are used
   (PERMISSIVE). Shell, Makefile and Dockerfile files are taken from every shard; C
   files from the first C_SHARDS shards only (the shards are a random sample, and all
   of C would be ~50 GB). Each shard is downloaded by a worker and deleted after use.
2. A curated list of well-known permissively licensed repositories (CURATED: BSD
   userlands, musl, toybox, suckless tools, sqlite, nginx, curl, tmux, openssh,
   oh-my-zsh, nvm, ...), shallow-cloned into data/raw/curated_repos/. Their files come
   first in the output, so they win exact/near-dup ties against GitHub copies.

Dropped: vendored/third-party/build paths, minified or generated files ("generated by",
"do not edit", ...), files under 100 bytes or over 200 KB, lines over 1000 characters,
data tables (mostly hex literals), very low alphanumeric content.
Each document is "File: <path>\\n\\n<code>"; meta has repo, path, language, licence.

A second source, code_c_more, adds the C files of shards 110-199 (deduplicated within
itself only), because the first pass came to 1.15B tokens against a 1.5B target.

Usage: .venv/bin/python -I data_tools/code.py [curated|github|finalize|c_more|all]
"""

